const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'test-results');
fs.mkdirSync(output, { recursive: true });
let server, browser;
(async () => {
  server = spawn('python3', ['-m', 'http.server', '4173', '--bind', '127.0.0.1'], { cwd:path.join(root,'dist'), stdio:'ignore' });
  let ready = false;
  for (let n=0;n<40;n++) { try { if ((await fetch('http://127.0.0.1:4173/')).ok) { ready=true; break; } } catch {} await new Promise(r=>setTimeout(r,100)); }
  assert.ok(ready,'Static server started');
  browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:390,height:844}, deviceScaleFactor:1});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:4173/';
  await page.goto(base+'#practice');
  await page.getByRole('heading',{name:'От вопроса к решению',exact:true}).waitFor();
  assert.equal(await page.locator('.practice-block').count(),12);
  assert.equal(await page.locator('.calc-card').count(),20);
  await page.screenshot({path:path.join(output,'practice-mobile.png'),fullPage:true});
  await page.locator('#practice-role').selectOption('industrial');
  await page.waitForURL('**/#practice/industrial');
  await page.waitForFunction(()=>document.querySelectorAll('.practice-block').length===5);
  await page.goto(base+'#exercise/TASK-010');
  await page.locator('#practice-draft').waitFor();
  const draft='x = v * dt\n<script>window.unsafeExecuted=true</script>';
  await page.locator('#practice-draft').fill(draft);
  await page.locator('#practice-coordinate_error').fill('0,096');
  await page.locator('#practice-reverse_error').fill('-0,096');
  await page.getByRole('button',{name:'Проверить все числа',exact:true}).click();
  assert.match(await page.locator('#practice-numbers-summary').textContent(),/2 из 2/);
  for(const box of await page.locator('[data-practice-criterion]').all()) await box.check();
  assert.equal(await page.locator('#practice-completion').textContent(),'Самопроверка выполнена');
  await page.reload();await page.locator('#practice-draft').waitFor();
  assert.equal(await page.locator('#practice-draft').inputValue(),draft);
  assert.equal(await page.locator('#practice-coordinate_error').inputValue(),'0,096');
  assert.equal(await page.evaluate(()=>window.unsafeExecuted),undefined);
  assert.equal(await page.locator('#practice-completion').textContent(),'Самопроверка выполнена');
  await page.locator('#practice-draft').fill('Исправленное объяснение');
  assert.equal(await page.locator('[data-practice-criterion]:checked').count(),0);
  await page.locator('#practice-coordinate_error').fill('96');
  await page.getByRole('button',{name:'Проверить: Ошибка при движении вперёд',exact:true}).click();
  assert.match(await page.locator('#result-coordinate_error').textContent(),/единиц/);
  await page.getByRole('button',{name:'Сообщить об ошибке в задаче'}).click();
  assert.match(await page.locator('#support-draft').inputValue(),/#exercise\/TASK-010/);
  assert.ok(!(await page.locator('#support-draft').inputValue()).includes('Исправленное объяснение'));
  await page.locator('#support-close').click();
  for(let n=1;n<=20;n++) {
    await page.goto(base+'#exercise/TASK-'+String(n).padStart(3,'0'));
    await page.locator('#practice-draft').waitFor();
    await page.waitForFunction(id=>document.querySelector('.question-tools span')?.textContent===id,'TASK-'+String(n).padStart(3,'0'));
    assert.ok(await page.locator('[data-practice-criterion]').count());
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'Overflow task '+n);
  }
  await page.goto(base+'#practice-block/int_ros2');
  await page.getByRole('button',{name:'Начать 5 вопросов',exact:true}).click();
  await page.waitForURL('**/#session');
  assert.equal(await page.locator('.answer').count(),4);
  const bank=JSON.parse(fs.readFileSync(path.join(root,'data/question_bank.json'),'utf8'));
  for(let n=0;n<5;n++) {
    const id=await page.evaluate(()=>JSON.parse(localStorage.getItem('robototehnika-bileti-ru:progress:v1')).active.questionIds[JSON.parse(localStorage.getItem('robototehnika-bileti-ru:progress:v1')).active.index]);
    const q=bank.questions.find(q=>q.id===id);
    await page.locator(`.answer[data-id="${q.correct_option_id}"]`).click();
    await page.locator('#next-question').click();
  }
  await page.getByRole('heading',{name:'Теперь решите задачу',exact:true}).waitFor();
  assert.equal(await page.locator('a[href="#exercise/TASK-013"]').count(),1);
  await page.goto(base+'#tickets');
  await page.getByRole('heading',{name:'Прикладные собеседования',exact:true}).waitFor();
  await page.locator('#ticket-mode').selectOption('exam');
  await page.locator('[data-action="begin-ticket"][data-id="INTERVIEW-03"]').click();
  await page.waitForURL('**/#session');
  assert.equal(await page.locator('.question-dot').count(),12);
  assert.equal(await page.locator('.practice-question-terms').count(),0);
  await page.getByRole('button',{name:'Сохранить и выйти'}).click();
  await page.setViewportSize({width:1440,height:980});
  await page.goto(base+'#exercise/TASK-007');await page.locator('#practice-draft').waitFor();
  await page.screenshot({path:path.join(output,'practice-desktop.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: mobile routes, 20 tasks, drafts/reload, XSS escaping, diagnostics, private feedback, profile filters, quiz-to-task transition, 12-question exam; no browser errors.');
  await browser.close();
})().catch(async e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser) await browser.close();if(server) server.kill('SIGTERM');});
